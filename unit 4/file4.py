# 21. Write a program to create, display, append, insert and reverse the order of the items in the array. 
array = []

# Create
array = [1, 2, 3, 4, 5]

# Display
print("Original array:", array)

# Append
array.append(6)
print("After appending 6:", array)

# Insert
array.insert(0, 0)
print("After inserting 0 at index 0:", array)

# Reverse
array.reverse()
print("After reversing:", array)